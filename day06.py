# Лекция 2. Loops. Циклы. 

# Цикл while и for. Пример использования цикла while. В данном примере цикл будет выполняться до тех пор, пока пользователь не введет положительное число.
while True:
    n = int(input("Введите число: "))
    if n > 0:
        break

for _ in range(n):
    print('meow')

# Цикл for. считаться будет от 0 до 9, так как в range(10) 10 не включительно.
for i in range(10):
    print(i, end = '\n') 